def table(t, label, Bs, ns, arms=ARMS):
    if t is None: return
    r = t['results']
    w('| %s n | B | R us/cfg/step [IQR] | ' % label + ' | '.join('%s/R' % a for a in arms if a != 'R') + ' |')
    w('|---|---|---|' + '---|' * (len(arms) - 1))
    for n in ns:
        for B in Bs:
            k = 'R|n%d|B%d' % (n, B)
            if k not in r: continue
            R = r[k]
            if 'error' in R:
                w('| %d | %d | R: %s |' % (n, B, R['error'][:60]) + ' |' * (len(arms) - 1)); continue
            cells = []
            for a in arms:
                if a == 'R': continue
                e = r.get('%s|n%d|B%d' % (a, n, B))
                cells.append('-' if e is None else ('FAILED: ' + e['error'][:40] if 'error' in e else '%.2f' % (e['median_s'] / R['median_s'])))
            w('| %d | %d | %.1f [%.1f, %.1f] | ' % (n, B, R['median_s'] * 1e6, R['q1_s'] * 1e6, R['q3_s'] * 1e6) + ' | '.join(cells) + ' |')
    w('')


