#!/usr/bin/env python3
"""20-site fixed-FN-amplitude, 360-label active acquisition ablation.

Requires the precomputed benchmark sign20_training_data.npz and the source
model generated by avsl_transfer20.py (avsl_transfer20_results.pt). Compare
random, source-confidence top, source uncertainty and signed-bond ranking.
Full exact FN amplitude backend: NOT on-policy/scalable yet.
"""
import os
os.environ.update(OPENBLAS_NUM_THREADS='1',OMP_NUM_THREADS='1',MKL_NUM_THREADS='1')
import json,time
import numpy as np,torch
from pathlib import Path
import avsl_transfer20 as T
from torch import nn
OUT=Path('/mnt/data/avsl_transfer20_active_acquisition_results.json')
N_PER=20
ARMS=['random','source_top','source_uncertainty','signed_bond']
old=torch.load('/mnt/data/avsl_transfer20_results.pt',map_location='cpu',weights_only=False)
torch.set_num_threads(2)
net=nn.Sequential(nn.Linear(13,32),nn.Tanh(),nn.Linear(32,32),nn.Tanh(),nn.Linear(32,1))
net.load_state_dict(old['full']);net.eval()
source=(net,old['full_mu'],old['full_std'])

def labels_for(arm):
    seen=set();xarr=[];yarr=[];cost=[]
    for seed in range(20260,20278):
        db,roots,pool,meta=T.frontier(seed,n_root=140)
        features,geom,signed=T.local_features(db,roots,pool,'post_krylov')
        candidates=np.array([i for i,g in enumerate(pool) if T.stable_split(g)!=0 and g not in seen],dtype=int)
        assert len(candidates)>=N_PER
        if arm=='random':
            ordered=np.random.default_rng(seed*47).permutation(candidates)
        elif arm=='source_top':
            logits=T.predict(source,features[candidates])
            ordered=candidates[np.argsort(-logits,kind='stable')]
        elif arm=='source_uncertainty':
            logits=T.predict(source,features[candidates])
            p=1/(1+np.exp(-np.clip(logits,-30,30)))
            ordered=candidates[np.argsort(np.abs(p-.5),kind='stable')]
        elif arm=='signed_bond':
            ordered=np.array(sorted(candidates,key=lambda i:(-signed[pool[i]],pool[i])),dtype=int)
        chosen=ordered[:N_PER];labs=[]
        before=len(db.amps)
        for ix in chosen:
            g=pool[ix];v,_=T.score(db,g,'post_krylov')
            labs.append(float(v>1e-13));seen.add(g)
        xarr.append(features[chosen]);yarr.append(np.asarray(labs,dtype=np.float32))
        cost.append(dict(seed=seed,label_queries=len(chosen),positive_labels=int(sum(labs)),
                         common_frontier_amp=len(db.amps),candidate_extra_amp=len(db.amps)-before,
                         common_frontier_pool=len(pool)))
    X=np.concatenate(xarr);Y=np.concatenate(yarr)
    return X,Y,cost

def finetune(X,Y,seed):
    torch.manual_seed(seed)
    m=nn.Sequential(nn.Linear(13,32),nn.Tanh(),nn.Linear(32,32),nn.Tanh(),nn.Linear(32,1))
    m.load_state_dict(old['full'])
    mu,std=old['full_mu'],old['full_std']
    xx=torch.tensor((X-mu)/std,dtype=torch.float32);yy=torch.tensor(Y,dtype=torch.float32)
    weight=float(min(15,max(1,((1-Y.mean())/max(Y.mean(),1e-5))**.5)))
    loss=nn.BCEWithLogitsLoss(pos_weight=torch.tensor(weight))
    optim=torch.optim.AdamW(m.parameters(),lr=.0008,weight_decay=.002)
    rng=np.random.default_rng(seed*389)
    for it in range(700):
        ix=rng.choice(len(Y),min(256,len(Y)),replace=True)
        value=loss(m(xx[ix]).flatten(),yy[ix]);optim.zero_grad();value.backward();optim.step()
    m.eval()
    return (m,mu,std),float(value.item())

trials=[]
for seed in range(30260,30280):
    db,roots,pool,meta=T.frontier(seed,n_root=140)
    test=[g for g in pool if T.stable_split(g)==0]
    f,_,_=T.local_features(db,roots,pool,'post_krylov')
    idx={g:i for i,g in enumerate(pool)}
    trials.append(dict(seed=seed,db=db,keys=test,features=f[[idx[g] for g in test]]))

def evaluate(model):
    data=[]
    for q in trials:
        lg=T.predict(model,q['features'])
        top=[q['keys'][int(i)] for i in np.argsort(-lg,kind='stable')[:22]]
        db=q['db'];raw={};edges={}
        for g in top:raw[g],edges[g]=T.score(db,g,'post_krylov')
        value,picks=T.greedy(raw,edges,top)
        data.append(dict(seed=q['seed'],top=[int(v) for v in top],
            gain=float(value/np.dot(T.AMPS,T.AMPS)),
            selected_keys=[int(g) for g in picks],
            beneficial=int(sum(v>1e-13 for v in raw.values()))))
    return dict(mean_gain=float(np.mean([v['gain'] for v in data])),
        mean_positive=float(np.mean([v['beneficial'] for v in data])),trials=data)

start=time.time()
out={'note':'Offline chamber-shift active label acquisition. Fixed exact FN amplitude oracle backend: NOT on-policy, RL or scalable. Every arm gets 360 labels; total frontier queries must also count. Heldout orbit split for training labels.', 'source_training_labels':1980,'label_budget_each':360,
     'train_episode_count':18,'test_episode_count':20,'eval_verify_budget':22,'arms':{}}
for arm in ARMS:
    X,Y,cost=labels_for(arm);results=[]
    for seed in (19,29):
        model,loss=finetune(X,Y,seed)
        metric=evaluate(model);metric['seed']=seed;metric['loss']=loss;results.append(metric)
    out['arms'][arm]=dict(labels=len(Y),positives=int(Y.sum()),
        total_frontier_amp_calls=sum(x['common_frontier_amp'] for x in cost),
        total_extra_label_amp_calls=sum(x['candidate_extra_amp'] for x in cost),
        training_cost=cost,
        mean_gain=float(np.mean([x['mean_gain'] for x in results])),models=results)
    print('ARM',arm,'positive',int(Y.sum()),'gains',
          [round(x['mean_gain'],9) for x in results],'time',round(time.time()-start,1),flush=True)
    OUT.write_text(json.dumps(out,indent=2))
print('RESULT SAVED',OUT,'WALL',round(time.time()-start,1))
