def ratio(t, a, n, B):
    if not t: return None
    r = t['results']; x = r.get('%s|n%d|B%d' % (a, n, B)); y = r.get('R|n%d|B%d' % (n, B))
    if not x or not y or 'error' in x or 'error' in y: return None
    return x['median_s'] / y['median_s']
